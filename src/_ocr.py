# ------------------------------------------------------------- PNG decode
import random
import struct
import zlib

SIGNATURE = b"\x89PNG\r\n\x1a\n"


def png_to_rgba(data):
    """Giai ma PNG 8-bit (color type 0/2/3/4/6) -> (w, h, rows[ (r,g,b,a) ])."""
    if not data.startswith(SIGNATURE):
        raise ValueError("Khong phai PNG")
    pos = 8
    width = height = bit = ctype = 0
    idat = b""
    palette = trns = None
    while pos + 8 <= len(data):
        (length,) = struct.unpack(">I", data[pos:pos + 4])
        tag = data[pos + 4:pos + 8]
        chunk = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if tag == b"IHDR":
            width, height, bit, ctype = struct.unpack(">IIBB", chunk[:10])
        elif tag == b"PLTE":
            palette = chunk
        elif tag == b"tRNS":
            trns = chunk
        elif tag == b"IDAT":
            idat += chunk
        elif tag == b"IEND":
            break
    if bit != 8:
        raise ValueError("PNG %s-bit khong ho tro" % bit)
    raw = zlib.decompress(idat)
    nch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}.get(ctype)
    if nch is None:
        raise ValueError("Color type khong ho tro: %s" % ctype)
    stride = width * nch
    out = []
    prev = bytearray(stride)
    p = 0
    for _y in range(height):
        ftype = raw[p]
        p += 1
        line = bytearray(raw[p:p + stride])
        p += stride
        if ftype == 1:
            for i in range(nch, stride):
                line[i] = (line[i] + line[i - nch]) & 0xFF
        elif ftype == 2:
            for i in range(stride):
                line[i] = (line[i] + prev[i]) & 0xFF
        elif ftype == 3:
            for i in range(stride):
                left = line[i - nch] if i >= nch else 0
                line[i] = (line[i] + ((left + prev[i]) >> 1)) & 0xFF
        elif ftype == 4:
            for i in range(stride):
                a = line[i - nch] if i >= nch else 0
                b = prev[i]
                c = prev[i - nch] if i >= nch else 0
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 0xFF
        prev = line
        row = []
        for x in range(width):
            o = x * nch
            if ctype == 6:
                row.append((line[o], line[o + 1], line[o + 2], line[o + 3]))
            elif ctype == 2:
                row.append((line[o], line[o + 1], line[o + 2], 255))
            elif ctype == 0:
                v = line[o]
                row.append((v, v, v, 255))
            elif ctype == 4:
                v = line[o]
                row.append((v, v, v, line[o + 1]))
            else:
                idx = line[o]
                if palette and idx * 3 + 2 < len(palette):
                    r, g, b = palette[idx * 3:idx * 3 + 3]
                else:
                    r = g = b = idx
                a = trns[idx] if (trns and idx < len(trns)) else 255
                row.append((r, g, b, a))
        out.append(row)
    return width, height, out


