def _blank():
    return [[0] * 16 for _ in range(18)]


class _Pen:
    def __init__(self):
        self.g = _blank()

    def h(self, y, x0, x1, t=1):
        for yy in range(y, y + t):
            for x in range(x0, x1 + 1):
                if 0 <= yy < 18 and 0 <= x < 16:
                    self.g[yy][x] = 1

    def v(self, x, y0, y1, t=1):
        for xx in range(x, x + t):
            for y in range(y0, y1 + 1):
                if 0 <= y < 18 and 0 <= xx < 16:
                    self.g[y][xx] = 1

    def d(self, x0, y0, x1, y1, t=1):
        steps = max(abs(x1 - x0), abs(y1 - y0))
        for i in range(steps + 1):
            x = int(round(x0 + (x1 - x0) * i / max(1, steps)))
            y = int(round(y0 + (y1 - y0) * i / max(1, steps)))
            self.v(x, y, y, t)
            self.h(y, x, x, t)


