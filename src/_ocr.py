def _lum(c):
    return (c[0] * 299 + c[1] * 587 + c[2] * 114) / 1000.0


def to_glyph_map(rgba, w, h):
    """Do dam cua chu so voi nen (bo duong ke mau, bo nhieu)."""
    hist = {}
    for y in range(h):
        for x in range(w):
            r, g, b, a = rgba[y][x]
            if a < 40:
                continue
            key = (r // 24, g // 24, b // 24)
            hist[key] = hist.get(key, 0) + 1
    bg = max(hist.items(), key=lambda kv: kv[1])[0]
    bg_l = _lum(((bg[0] + 0.5) * 24, (bg[1] + 0.5) * 24, (bg[2] + 0.5) * 24))
    dark_chars = bg_l > 110
    grid = []
    for y in range(h):
        line = []
        for x in range(w):
            r, g, b, a = rgba[y][x]
            if a < 40:
                line.append(0)
                continue
            l = _lum((r, g, b))
            v = (bg_l - l) if dark_chars else (l - bg_l)
            v = int(max(0, min(255, v * 3.0)))
            line.append(v)
        grid.append(line)
    return grid


def _otsu(grid, h, w):
    hist = [0] * 256
    for y in range(h):
        for x in range(w):
            hist[grid[y][x]] += 1
    total = h * w
    sum_all = sum(i * hist[i] for i in range(256))
    sum_b = wb = best = 0
    thr = 128
    for t in range(256):
        wb += hist[t]
        if wb == 0:
            continue
        wf = total - wb
        if wf == 0:
            break
        sum_b += t * hist[t]
        mb = sum_b / wb
        mf = (sum_all - sum_b) / wf
        var = wb * wf * (mb - mf) ** 2
        if var > best:
            best = var
            thr = t
    return max(45, min(190, thr))


def binarize(grid, h, w):
    thr = _otsu(grid, h, w)
    return [[1 if grid[y][x] >= thr else 0 for x in range(w)] for y in range(h)]


def columns(binimg, h, w):
    return [sum(binimg[y][x] for y in range(h)) for x in range(w)]


def rows_of(binimg, h, w):
    return [sum(binimg[y][x] for x in range(w)) for y in range(h)]


def crop(binimg, x0, x1, y0, y1):
    x0, x1 = max(0, x0), min(len(binimg[0]), x1)
    return [row[x0:x1] for row in binimg[max(0, y0):y1]]


def resize(img, tw, th):
    h = len(img)
    w = len(img[0]) if h else 0
    if not h or not w:
        return [[0] * tw for _ in range(th)]
    out = []
    for j in range(th):
        src = img[min(h - 1, int(j * h / th))]
        line = []
        for i in range(tw):
            line.append(src[min(w - 1, int(i * w / tw))])
        out.append(line)
    return out


def normalize(img, tw=8, th=12):
    """Cat theo vien chu roi keo ve kich thuoc co dinh."""
    h = len(img)
    w = len(img[0]) if h else 0
    ys = [y for y in range(h) if any(img[y][x] for x in range(w))]
    xs = [x for x in range(w) if any(img[y][x] for y in range(h))]
    if not ys or not xs:
        return [[0] * tw for _ in range(th)]
    body = [row[xs[0]:xs[-1] + 1] for row in img[ys[0]:ys[-1] + 1]]
    return resize(body, tw, th)


def _segment(binimg, h, w):
    cols = columns(binimg, h, w)
    peak = max(cols) if cols else 0
    if peak <= 0:
        return [], 0, h
    thr = max(1, int(peak * 0.12))
    spans = []
    start = None
    for x in range(w):
        on = cols[x] >= thr
        if on and start is None:
            start = x
        elif not on and start is not None:
            if x - start >= 3:
                spans.append([start, x])
            start = None
    if start is not None and w - start >= 3:
        spans.append([start, w])
    while len(spans) > 5 and len(spans) > 1:
        gaps = sorted((spans[i + 1][0] - spans[i][1], i) for i in range(len(spans) - 1))
        i = gaps[0][1]
        spans[i][1] = spans[i + 1][1]
        del spans[i + 1]
    rws = rows_of(binimg, h, w)
    lim = max(1, int(peak * 0.05))
    ys = [y for y in range(h) if rws[y] >= lim]
    return spans, (ys[0] if ys else 0), (ys[-1] + 1 if ys else h)


