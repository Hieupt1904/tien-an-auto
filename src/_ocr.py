    for (x0, x1) in spans:
        piece = normalize(crop(binimg, x0 - 1, x1 + 1, y0, y1), _G, _H)
        best = None
        for font in _FONTS.values():
            for digit, tmpl in font.items():
                s = match_score(piece, tmpl)
                if best is None or s > best[0]:
                    best = (s, digit)
        out.append(_label(best[1]))
        scores.append(best[0])
    if not out:
        return "", 0.0
    return "".join(out), sum(scores) / len(scores)


