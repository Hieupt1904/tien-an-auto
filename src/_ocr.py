def _art(img):
    out = []
    for row in img:
        out.append("".join("#" if v else "_" for v in row))
    return out


def _augment(img, rng):
    """Sinh bien the: lech 1px, phong to/thu nho."""
    h = len(img)
    w = len(img[0])
    dx = rng.choice((-1, 0, 0, 1))
    dy = rng.choice((-1, 0, 0, 1))
    fat = rng.random() < 0.35
    out = [[0] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if not img[y][x]:
                continue
            for ox, oy in ((0, 0), (1, 0), (0, 1), (1, 1)) if fat else ((0, 0),):
                ny, nx = y + dy + oy, x + dx + ox
                if 0 <= ny < h and 0 <= nx < w:
                    out[ny][nx] = 1
    return out


def dump_art(png_bytes):
    """Chuoi nhi phan de nguoi dung dan tay vao ban do _RAW."""
    w, h, rgba = png_to_rgba(png_bytes)
    grid = to_glyph_map(rgba, w, h)
    binimg = binarize(grid, h, w)
    spans, y0, y1 = _segment(binimg, h, w)
    return [_art(normalize(crop(binimg, x0, x1, y0, y1), _G, _H)) for (x0, x1) in spans]


