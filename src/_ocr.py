def match_score(got, tmpl):
    h = min(len(got), len(tmpl))
    w = min(len(got[0]), len(tmpl[0]))
    same = 0
    for y in range(h):
        for x in range(w):
            if got[y][x] == tmpl[y][x]:
                same += 1
    return same / float(h * w or 1)


